"""Unit and integration tests for NOVA Phase 12: HuggingFace GGUF Auto-Discovery & Live Qwen 3.5 9B Adapter (`test_gguf_live.py`).

Verifies:
1. `discover_local_gguf_models` scans a HuggingFace-style snapshot folder containing both
   `qwen3.5-9b-Q4_K_M.gguf` and `mmproj-qwen3.5-9b-BF16.gguf`, automatically pairing the primary
   9B LLM weights with the `mmproj` vision projector.
2. `generate_ollama_modelfile` produces a valid Ollama `Modelfile` pointing directly to the local
   `qwen3.5-9b-Q4_K_M.gguf` path without re-downloading.
3. `LiveGgufModelAdapter` executes structured NOVA proposals using a live GGUF completion callback
   (and falls back cleanly to `RuleGuidedLocalBootstrapAdapter` if no GGUF runtime is active).
"""

from __future__ import annotations

import json
import tempfile
from pathlib import Path
from typing import Dict, List

from nova.core.domain.primitives import AgentRole
from nova.core.model_serving.gguf_live import (
    LiveGgufModelAdapter,
    discover_local_gguf_models,
    generate_ollama_modelfile,
    inspect_local_gguf_brain_status,
)
from nova.core.model_serving.interface import ModelInferenceRequest


class TestGgufDiscoveryAndQwenAdapter:
    """Verification suite for Phase 12 (`services/backend/src/nova/core/model_serving/gguf_live.py`)."""

    def test_discover_qwen35_gguf_and_mmproj_from_huggingface_cache_layout(self) -> None:
        """Simulates the exact HuggingFace cache layout for Qwen3.5-9B-GGUF and verifies pairing."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            snap_dir = (
                Path(tmp_dir)
                / "models--gguf--Qwen3.5-9B-GGUF"
                / "snapshots"
                / "dc40af5d4666acd6ce1c1dd71ec61cee2f1c966e"
            )
            snap_dir.mkdir(parents=True, exist_ok=True)

            llm_file = snap_dir / "qwen3.5-9b-Q4_K_M.gguf"
            mmproj_file = snap_dir / "mmproj-qwen3.5-9b-BF16.gguf"
            llm_file.write_bytes(b"GGUF_FAKE_LLM_WEIGHTS" * 100)
            mmproj_file.write_bytes(b"GGUF_FAKE_MMPROJ_WEIGHTS" * 50)

            bundles = discover_local_gguf_models(search_root=Path(tmp_dir))
            assert len(bundles) == 1
            bundle = bundles[0]
            assert bundle.model_name == "qwen3.5-9b-Q4_K_M"
            assert bundle.llm_gguf_path == llm_file.resolve()
            assert bundle.mmproj_gguf_path == mmproj_file.resolve()

            status = inspect_local_gguf_brain_status(search_root=Path(tmp_dir))
            assert status["gguf_found"] is True
            assert status["primary_model_name"] == "qwen3.5-9b-Q4_K_M"
            assert "qwen3.5-9b-Q4_K_M.gguf" in status["primary_llm_gguf_path"]
            assert "mmproj-qwen3.5-9b-BF16.gguf" in str(status["mmproj_vision_gguf_path"])

            modelfile = generate_ollama_modelfile(bundle)
            assert f'FROM "{llm_file.resolve()}"' in modelfile
            assert "PARAMETER temperature 0" in modelfile

    def test_live_gguf_model_adapter_normalizes_qwen_json_and_falls_back_cleanly(
        self,
    ) -> None:
        """Verifies LiveGgufModelAdapter uses Qwen GGUF output when available and falls back when offline."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            llm_file = Path(tmp_dir) / "qwen3.5-9b-Q4_K_M.gguf"
            llm_file.write_bytes(b"GGUF_WEIGHTS")
            bundle = discover_local_gguf_models(explicit_gguf_path=llm_file)[0]

            gguf_active = {"online": True}

            def fake_qwen_gguf_completion(messages: List[Dict[str, str]]) -> str:
                if not gguf_active["online"]:
                    raise RuntimeError("GGUF runtime not started")
                return json.dumps(
                    {
                        "kind": "final_answer",
                        "thought": "Qwen 3.5 9B analyzed the request.",
                        "content": "Response generated by Qwen 3.5 9B Q4_K_M GGUF!",
                    }
                )

            adapter = LiveGgufModelAdapter(
                bundle=bundle,
                completion_fn=fake_qwen_gguf_completion,
            )
            req = ModelInferenceRequest(
                task_id="task_qwen_01",
                session_id="sess_qwen_01",
                node_id="step_research_info",
                agent_role=AgentRole.RESEARCH,
                messages=(
                    {
                        "role": "system",
                        "content": "[NOVA TRUSTED SYSTEM INSTRUCTION]\nTask Objective: Summarize Qwen 3.5",
                    },
                ),
                output_schema_name="AgentProposal",
            )

            # 1. Live Qwen 3.5 9B GGUF completion
            resp_live = adapter.generate_structured(req)
            assert adapter.gguf_calls_succeeded == 1
            assert adapter.fallback_calls_used == 0
            assert "Response generated by Qwen 3.5 9B Q4_K_M GGUF!" in str(resp_live.raw_output)

            # 2. Automatic fallback when GGUF runtime is offline
            gguf_active["online"] = False
            resp_fallback = adapter.generate_structured(req)
            assert adapter.gguf_calls_succeeded == 1
            assert adapter.fallback_calls_used == 1
            assert "tool_call" in str(resp_fallback.raw_output)